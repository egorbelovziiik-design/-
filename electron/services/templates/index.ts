function discordBotFiles(v: TemplateVars): ProjectTemplateFile[] {
  return [
    {
      path: 'package.json',
      content: JSON.stringify(
        {
          name: v.projectName.toLowerCase().replace(/[^a-z0-9-]/g, '-'),
          version: v.modVersion ?? '1.0.0',
          type: 'module',
          scripts: { start: 'node src/index.js', dev: 'node --watch src/index.js' },
          dependencies: { 'discord.js': '^14.16.3' },
        },
        null,
        2,
      ),
    },
    {
      path: 'src/index.js',
      content: `import { Client, GatewayIntentBits, Events, EmbedBuilder } from 'discord.js';

const client = new Client({
  intents: [GatewayIntentBits.Guilds, GatewayIntentBits.GuildMessages, GatewayIntentBits.MessageContent],
});

client.once(Events.ClientReady, (c) => console.log(\`Logged in as \${c.user.tag} — generated by WinCode AI\`));

client.on(Events.MessageCreate, async (message) => {
  if (message.author.bot) return;
  if (message.content === '!ping') {
    await message.reply('Pong! 🏓');
  }
  if (message.content === '!help') {
    const embed = new EmbedBuilder()
      .setTitle('${v.projectName}')
      .setDescription('Bot generated by WinCode AI')
      .setColor(0x9333EA)
      .addFields({ name: 'Commands', value: '!ping — latency check\\n!help — this message' });
    await message.reply({ embeds: [embed] });
  }
});

if (!process.env.DISCORD_TOKEN) {
  console.error('Set the DISCORD_TOKEN environment variable.');
  process.exit(1);
}
client.login(process.env.DISCORD_TOKEN);
`,
    },
    { path: '.env.example', content: 'DISCORD_TOKEN=your-token-here\n' },
    { path: '.gitignore', content: 'node_modules/\n.env\n' },
    {
      path: 'README.md',
      content: `# ${v.projectName}\n\nDiscord bot generated by WinCode AI (discord.js v14).\n\n\`\`\`bash\nnpm install\ncp .env.example .env   # put your token\nnpm start\n\`\`\`\n`,
    },
  ];
}

