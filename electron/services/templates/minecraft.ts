import type { ProjectTemplateFile, TemplateVars } from '../../shared/types';
import { compatFor, gradleWrapperProperties, GRADLEW_SH, GRADLEW_BAT } from './mcVersions';

function pkgPath(pkg: string): string {
  return pkg.replace(/\./g, '/');
}

function gradlePropertiesFabric(v: TemplateVars): string {
  const c = compatFor(v.minecraftVersion ?? '1.21.4');
  return `# Generated by WinCode AI — Minecraft Development Center
org.gradle.jvmargs=-Xmx2G
minecraft_version=${c.minecraft}
yarn_mappings=${c.yarn}
loader_version=${c.fabricLoader}
fabric_version=${c.fabricApi}
mod_version=${v.modVersion ?? '1.0.0'}
maven_group=${v.packageName}
archives_base_name=${v.projectName.toLowerCase().replace(/[^a-z0-9-]/g, '-')}-fabric
`;
}

function buildGradleFabric(v: TemplateVars): string {
  const c = compatFor(v.minecraftVersion ?? '1.21.4');
  return `plugins {
    id 'fabric-loom' version '${c.loom}'
    id 'maven-publish'
}

version = project.mod_version
group = project.maven_group

base {
    archivesName = project.archives_base_name
}

repositories {
    mavenCentral()
}

dependencies {
    minecraft "com.mojang:minecraft:\${project.minecraft_version}"
    mappings "net.fabricmc:yarn:\${project.yarn_mappings}:v2"
    modImplementation "net.fabricmc:fabric-loader:\${project.fabric_loader}"
    modImplementation "net.fabricmc.fabric-api:fabric-api:\${project.fabric_api}"
}

processResources {
    inputs.property "version", project.version
    filteringCharset "UTF-8"
    filesMatching("fabric.mod.json") {
        expand "version": project.version
    }
}

tasks.withType(JavaCompile).configureEach {
    it.options.release = ${c.java}
    it.options.encoding = "UTF-8"
}

java {
    sourceCompatibility = JavaVersion.VERSION_${c.java === '8' ? '1_8' : c.java === '17' ? '17' : '21'}
    targetCompatibility = JavaVersion.VERSION_${c.java === '8' ? '1_8' : c.java === '17' ? '17' : '21'}
    withSourcesJar()
}

jar {
    from("LICENSE") {
        rename { "\${it}_\${project.base.archivesName.get()}" }
    }
}
`;
}

