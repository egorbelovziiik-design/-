import { useState, useEffect } from 'react';
import { X, Sparkles, FolderOpen, Pickaxe, Code2, Globe, Bot, Cpu, Loader2, ChevronRight, FileCode2 } from 'lucide-react';
import { useApp } from '../state/store';
import type { MCVersionCompat } from '@shared/types';

interface TemplateInfo {
  id: string;
  name: string;
  category: string;
  description: string;
  languages: string[];
}

const categoryIcons: Record<string, typeof Pickaxe> = {
  minecraft: Pickaxe,
  general: Code2,
  web: Globe,
  ai: Bot,
};

export default function NewProjectWizard() {
  const open = useApp((s) => s.wizardOpen);
  const setOverlay = useApp((s) => s.setOverlay);
  const openWorkspace = useApp((s) => s.openWorkspace);
  const notify = useApp((s) => s.notify);
  const settings = useApp((s) => s.settings);

  const [templates, setTemplates] = useState<TemplateInfo[]>([]);
  const [versions, setVersions] = useState<MCVersionCompat[]>([]);
  const [selected, setSelected] = useState('minecraft-visual-client');
  const [name, setName] = useState('MyProject');
  const [location, setLocation] = useState('');
  const [pkg, setPkg] = useState('com.example.myproject');
  const [mcVersion, setMcVersion] = useState(settings?.minecraft.defaultMinecraftVersion ?? '1.21.4');
  const [loader, setLoader] = useState('fabric');
  const [author, setAuthor] = useState('');
  const [description, setDescription] = useState('');
  const [busy, setBusy] = useState(false);
  const [step, setStep] = useState<0 | 1>(0);

  useEffect(() => {
    if (!open) return;
    void window.wincode.listTemplates().then(setTemplates);
    void window.wincode.mcVersions().then(setVersions);
  }, [open]);

  if (!open) return null;

  const isMinecraft = templates.find((t) => t.id === selected)?.category === 'minecraft';
  const compat = versions.find((v) => v.minecraft === mcVersion);

  const create = async () => {
    if (!location) {
      notify('warning', 'Choose a project location folder first');
      return;
    }
    setBusy(true);
    try {
      const target = `${location.replace(/[\\/]+$/, '')}/${name}`;
      const res = await window.wincode.createProject(target, selected, {
        projectName: name,
        packageName: pkg,
        minecraftVersion: mcVersion,
        loader,
        javaVersion: compat?.java ?? '21',
        modVersion: '1.0.0',
        author: author || 'WinCode AI User',
        description: description || `${name} — generated by WinCode AI`,
      });
      notify('success', `Project created: ${res.files} files`);
      setOverlay('wizard', false);
      await openWorkspace(res.root);
      setStep(0);
    } catch (err) {
      notify('error', 'Project creation failed', (err as Error).message);
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="fixed inset-0 z-[70] flex items-center justify-center" style={{ background: 'rgba(0,0,0,0.55)' }} onClick={() => setOverlay('wizard', false)}>
      <div
        className="flex h-[640px] w-[920px] max-w-[95vw] overflow-hidden rounded-2xl border shadow-panel animate-fade-in"
        style={{ background: 'var(--wc-panel)', borderColor: 'var(--wc-border)' }}
        onClick={(e) => e.stopPropagation()}
      >
        {/* template list */}
        <div className="w-[300px] shrink-0 overflow-y-auto p-4" style={{ borderRight: '1px solid var(--wc-border)' }}>
          <div className="flex items-center gap-2">
            <div className="flex h-8 w-8 items-center justify-center rounded-lg" style={{ background: 'linear-gradient(135deg,#9333EA,#A855F7)' }}>
              <Sparkles size={16} color="white" />
            </div>
            <div>
              <div className="text-[13px] font-semibold">New Project</div>
              <div className="text-[10px]" style={{ color: 'var(--wc-muted)' }}>Choose a template</div>
            </div>
          </div>

          <div className="mt-4 space-y-4">
            {(['minecraft', 'general', 'web'] as const).map((cat) => (
              <div key={cat}>
                <div className="mb-1.5 text-[10px] font-semibold uppercase tracking-wider" style={{ color: 'var(--wc-muted)' }}>
                  {cat}
                </div>
                {templates
                  .filter((t) => t.category === cat)
                  .map((t) => {
                    const Icon = categoryIcons[t.category] ?? Code2;
                    const active = selected === t.id;
                    return (
                      <button
                        key={t.id}
                        className="mb-1 flex w-full items-start gap-2 rounded-lg p-2 text-left transition-colors"
                        style={{
                          background: active ? 'var(--wc-active)' : 'transparent',
                          border: active ? '1px solid var(--wc-accent)' : '1px solid transparent',
                        }}
                        onClick={() => {
                          setSelected(t.id);
                          setStep(1);
                        }}
                      >
                        <Icon size={14} className="mt-0.5 shrink-0" style={{ color: active ? 'var(--wc-neon)' : 'var(--wc-muted)' }} />
                        <div className="min-w-0">
                          <div className="truncate text-[11px] font-medium">{t.name}</div>
                          <div className="line-clamp-2 text-[9.5px] leading-snug" style={{ color: 'var(--wc-muted)' }}>
                            {t.description}
                          </div>
                        </div>
                      </button>
                    );
                  })}
              </div>
            ))}
          </div>
        </div>

        {/* config */}
        <div className="flex flex-1 flex-col">
          <div className="flex items-center justify-between px-5 pt-4">
            <div>
              <div className="text-[15px] font-semibold">{templates.find((t) => t.id === selected)?.name ?? 'Project'}</div>
              <div className="text-[10.5px]" style={{ color: 'var(--wc-muted)' }}>
                {templates.find((t) => t.id === selected)?.description}
              </div>
            </div>
            <button className="rounded-lg p-1.5 hover:bg-white/10" onClick={() => setOverlay('wizard', false)}>
              <X size={16} />
            </button>
          </div>

          <div className="flex-1 space-y-3.5 overflow-y-auto px-5 py-4">
            <div>
              <label className="mb-1 block text-[10.5px] font-medium" style={{ color: 'var(--wc-muted)' }}>Project name</label>
              <input className="wc-input w-full" value={name} onChange={(e) => {
                setName(e.target.value);
                setPkg(`com.example.${e.target.value.toLowerCase().replace(/[^a-z0-9]/g, '') || 'myproject'}`);
              }} />
            </div>

            <div>
              <label className="mb-1 block text-[10.5px] font-medium" style={{ color: 'var(--wc-muted)' }}>Location</label>
              <div className="flex gap-2">
                <input className="wc-input flex-1" placeholder="C:\Projects" value={location} onChange={(e) => setLocation(e.target.value)} />
                <button
                  className="wc-btn"
                  onClick={async () => {
                    const dir = await window.wincode.pickFolder();
                    if (dir) setLocation(dir);
                  }}
                >
                  <FolderOpen size={13} /> Browse
                </button>
              </div>
            </div>

            <div>
              <label className="mb-1 block text-[10.5px] font-medium" style={{ color: 'var(--wc-muted)' }}>Package / group</label>
              <input className="wc-input w-full font-mono text-[11.5px]" value={pkg} onChange={(e) => setPkg(e.target.value)} />
            </div>

            {isMinecraft && (
              <>
                <div className="grid grid-cols-2 gap-3">
                  <div>
                    <label className="mb-1 block text-[10.5px] font-medium" style={{ color: 'var(--wc-muted)' }}>Minecraft version</label>
                    <select className="wc-input w-full" value={mcVersion} onChange={(e) => setMcVersion(e.target.value)}>
                      {versions.map((v) => (
                        <option key={v.minecraft} value={v.minecraft}>
                          {v.minecraft} · Java {v.java}
                        </option>
                      ))}
                    </select>
                  </div>
                  <div>
                    <label className="mb-1 block text-[10.5px] font-medium" style={{ color: 'var(--wc-muted)' }}>Mod loader</label>
                    <select className="wc-input w-full" value={loader} onChange={(e) => setLoader(e.target.value)}>
                      <option value="fabric">Fabric</option>
                      <option value="forge">Forge</option>
                      <option value="neoforge">NeoForge</option>
                      <option value="quilt">Quilt</option>
                    </select>
                  </div>
                </div>
                {compat && (
                  <div className="rounded-lg border p-2.5 text-[10px] leading-relaxed" style={{ borderColor: 'var(--wc-border)', background: 'var(--wc-editor)', color: 'var(--wc-muted)' }}>
                    <Cpu size={10} className="mr-1 inline" />
                    Verified versions — Fabric Loader <b>{compat.fabricLoader}</b>, Fabric API <b>{compat.fabricApi}</b>,
                    Yarn <b>{compat.yarn}</b>, Loom <b>{compat.loom}</b>, Forge <b>{compat.forge}</b>, NeoForge <b>{compat.neoforge}</b>, Java{' '}
                    <b>{compat.java}</b>
                  </div>
                )}
              </>
            )}

            <div className="grid grid-cols-2 gap-3">
              <div>
                <label className="mb-1 block text-[10.5px] font-medium" style={{ color: 'var(--wc-muted)' }}>Author</label>
                <input className="wc-input w-full" value={author} onChange={(e) => setAuthor(e.target.value)} placeholder="Your name" />
              </div>
              <div>
                <label className="mb-1 block text-[10.5px] font-medium" style={{ color: 'var(--wc-muted)' }}>Description</label>
                <input className="wc-input w-full" value={description} onChange={(e) => setDescription(e.target.value)} placeholder="Optional" />
              </div>
            </div>
          </div>

          <div className="flex items-center gap-2 px-5 pb-4 pt-2">
            <div className="text-[10px]" style={{ color: 'var(--wc-muted)' }}>
              {step === 0 ? 'Select a template on the left' : 'Ready to create'}
            </div>
            <button className="wc-btn ml-auto" onClick={() => setOverlay('wizard', false)}>
              Cancel
            </button>
            <button className="wc-btn wc-btn-primary px-5" disabled={busy || !name || !location} onClick={() => void create()}>
              {busy ? <Loader2 size={13} className="spin" /> : <FileCode2 size={13} />} Create Project <ChevronRight size={12} />
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
