import { useState, useRef } from 'react';
import {
  X,
  Square,
  Type,
  MousePointerClick,
  ToggleLeft,
  SlidersHorizontal,
  PanelTop,
  CreditCard,
  Image,
  Code2,
  Copy,
  Save,
  Undo2,
  Sparkles,
} from 'lucide-react';
import { useApp } from '../state/store';

interface GuiComponent {
  id: string;
  kind: 'button' | 'label' | 'input' | 'toggle' | 'slider' | 'panel' | 'card' | 'image';
  x: number;
  y: number;
  w: number;
  h: number;
  text: string;
  color: string;
}

const palette: { kind: GuiComponent['kind']; icon: typeof Square; label: string }[] = [
  { kind: 'button', icon: MousePointerClick, label: 'Button' },
  { kind: 'label', icon: Type, label: 'Text' },
  { kind: 'input', icon: Square, label: 'Input' },
  { kind: 'toggle', icon: ToggleLeft, label: 'Toggle' },
  { kind: 'slider', icon: SlidersHorizontal, label: 'Slider' },
  { kind: 'panel', icon: PanelTop, label: 'Panel' },
  { kind: 'card', icon: CreditCard, label: 'Card' },
  { kind: 'image', icon: Image, label: 'Image' },
];

type OutputKind = 'html' | 'swing' | 'minecraft';

function generateCode(components: GuiComponent[], target: OutputKind, name: string): string {
  if (target === 'html') {
    const items = components
      .map((c) => {
        const style = `position:absolute;left:${c.x}px;top:${c.y}px;width:${c.w}px;height:${c.h}px;`;
        switch (c.kind) {
          case 'button':
            return `  <button class="wc-btn" style="${style}background:${c.color};color:#fff;border:0;border-radius:10px;cursor:pointer;">${c.text}</button>`;
          case 'label':
            return `  <div style="${style}color:#E5E7EB;font:14px 'Segoe UI',sans-serif;display:flex;align-items:center;">${c.text}</div>`;
          case 'input':
            return `  <input placeholder="${c.text}" style="${style}background:#11111B;color:#E5E7EB;border:1px solid #1f1f2e;border-radius:8px;padding:0 10px;outline:none;" />`;
          case 'toggle':
            return `  <label style="${style}display:flex;align-items:center;gap:8px;color:#E5E7EB;font:12px 'Segoe UI',sans-serif;"><input type="checkbox" checked /> ${c.text}</label>`;
          case 'slider':
            return `  <input type="range" min="0" max="100" value="50" style="${style}" />`;
          case 'panel':
            return `  <div style="${style}background:#11111B;border:1px solid #1f1f2e;border-radius:14px;"></div>`;
          case 'card':
            return `  <div style="${style}background:linear-gradient(135deg,${c.color},#A855F7);border-radius:14px;box-shadow:0 10px 30px rgba(147,51,234,.35);"></div>`;
          case 'image':
            return `  <img alt="${c.text}" src="assets/${c.text || 'image'}.png" style="${style}object-fit:cover;border-radius:10px;" />`;
          default:
            return '';
        }
      })
      .join('\n');
    return `<!doctype html>
<!-- ${name} — generated by WinCode AI GUI Builder -->
<html>
<head>
  <meta charset="utf-8" />
  <title>${name}</title>
  <style>
    body { margin:0; min-height:100vh; background:#09090F; overflow:hidden; }
  </style>
</head>
<body>
${items}
</body>
</html>
`;
  }

  if (target === 'swing') {
    const items = components
      .map((c) => {
        switch (c.kind) {
          case 'button':
            return `        JButton ${id(c)} = new JButton("${c.text}");\n        ${id(c)}.setBounds(${c.x}, ${c.y}, ${c.w}, ${c.h});\n        ${id(c)}.setBackground(new Color(0x${c.color.replace('#', '')}));\n        ${id(c)}.setFocusPainted(false);\n        panel.add(${id(c)});`;
          case 'label':
            return `        JLabel ${id(c)} = new JLabel("${c.text}");\n        ${id(c)}.setBounds(${c.x}, ${c.y}, ${c.w}, ${c.h});\n        panel.add(${id(c)});`;
          case 'input':
            return `        JTextField ${id(c)} = new JTextField("${c.text}");\n        ${id(c)}.setBounds(${c.x}, ${c.y}, ${c.w}, ${c.h});\n        panel.add(${id(c)});`;
          case 'toggle':
            return `        JCheckBox ${id(c)} = new JCheckBox("${c.text}");\n        ${id(c)}.setBounds(${c.x}, ${c.y}, ${c.w}, ${c.h});\n        panel.add(${id(c)});`;
          case 'slider':
            return `        JSlider ${id(c)} = new JSlider(0, 100, 50);\n        ${id(c)}.setBounds(${c.x}, ${c.y}, ${c.w}, ${c.h});\n        panel.add(${id(c)});`;
          case 'panel':
          case 'card':
            return `        JPanel ${id(c)} = new JPanel();\n        ${id(c)}.setBounds(${c.x}, ${c.y}, ${c.w}, ${c.h});\n        ${id(c)}.setBackground(new Color(0x${c.color.replace('#', '')}));\n        panel.add(${id(c)});`;
          default:
            return '';
        }
      })
      .join('\n');
    return `// ${name} — generated by WinCode AI GUI Builder
import javax.swing.*;
import java.awt.*;

public class ${name.replace(/[^A-Za-z0-9]/g, '')}Frame extends JFrame {
    public ${name.replace(/[^A-Za-z0-9]/g, '')}Frame() {
        setTitle("${name}");
        setSize(800, 560);
        setDefaultCloseOperation(EXIT_ON_CLOSE);
        setLayout(null);

        JPanel panel = new JPanel(null);
        panel.setBackground(new Color(0x09090F));
        panel.setBounds(0, 0, 800, 560);
        setContentPane(panel);

${items}

        setLocationRelativeTo(null);
    }

    public static void main(String[] args) {
        SwingUtilities.invokeLater(() -> new ${name.replace(/[^A-Za-z0-9]/g, '')}Frame().setVisible(true));
    }
}
`;
  }

  // Minecraft GUI (Yarn 1.21.x)
  const draws = components
    .map((c) => {
      switch (c.kind) {
        case 'button':
          return `        drawRounded(context, ${c.x}, ${c.y}, ${c.w}, ${c.h}, 8, 0xFF${c.color.replace('#', '')});\n        context.drawTextWithShadow(textRenderer, "${c.text}", ${c.x + 12}, ${c.y + Math.round(c.h / 2) - 4}, 0xFFFFFF);`;
        case 'label':
          return `        context.drawTextWithShadow(textRenderer, "${c.text}", ${c.x}, ${c.y}, 0xE5E7EB);`;
        case 'panel':
        case 'card':
          return `        drawRounded(context, ${c.x}, ${c.y}, ${c.w}, ${c.h}, 12, 0xFF${c.color.replace('#', '')});`;
        case 'toggle':
          return `        context.drawTextWithShadow(textRenderer, "${c.text}", ${c.x + 18}, ${c.y}, 0xE5E7EB);\n        drawRounded(context, ${c.x}, ${c.y - 2}, 12, 12, 6, 0xFFA855F7);`;
        default:
          return `        // ${c.kind}: ${c.text} at (${c.x}, ${c.y})`;
      }
    })
    .join('\n');

  return `// ${name} — Minecraft GUI generated by WinCode AI GUI Builder
// Yarn mappings for Minecraft 1.21.x (Fabric)
package com.example.client.gui;

import net.minecraft.client.gui.DrawContext;
import net.minecraft.client.gui.screen.Screen;
import net.minecraft.text.Text;

public class ${name.replace(/[^A-Za-z0-9]/g, '')}Screen extends Screen {
    public ${name.replace(/[^A-Za-z0-9]/g, '')}Screen() {
        super(Text.literal("${name}"));
    }

    @Override
    public void render(DrawContext context, int mouseX, int mouseY, float delta) {
        context.fillGradient(0, 0, width, height, 0xCC09090F, 0xE609090F);
${draws}
        super.render(context, mouseX, mouseY, delta);
    }

    private void drawRounded(DrawContext context, int x, int y, int w, int h, int r, int color) {
        context.fill(x + r, y, x + w - r, y + h, color);
        context.fill(x, y + r, x + w, y + h - r, color);
    }

    @Override
    public boolean shouldPause() {
        return false;
    }
}
`;
}

function id(c: GuiComponent): string {
  return `${c.kind}${c.id.replace(/[^a-zA-Z0-9]/g, '')}`;
}

export default function GuiBuilder() {
  const open = useApp((s) => s.guiBuilderOpen);
  const setOverlay = useApp((s) => s.setOverlay);
  const notify = useApp((s) => s.notify);
  const workspaceRoot = useApp((s) => s.workspaceRoot);
  const [components, setComponents] = useState<GuiComponent[]>([
    { id: 'c1', kind: 'card', x: 40, y: 30, w: 260, h: 120, text: '', color: '#9333EA' },
    { id: 'c2', kind: 'label', x: 60, y: 50, w: 200, h: 24, text: 'WinCode ClickGUI', color: '#A855F7' },
    { id: 'c3', kind: 'button', x: 60, y: 90, w: 120, h: 34, text: 'Enable', color: '#9333EA' },
  ]);
  const [selected, setSelected] = useState<string | null>(null);
  const [target, setTarget] = useState<OutputKind>('html');
  const [name, setName] = useState('MyGui');
  const [preview, setPreview] = useState<string | null>(null);
  const dragRef = useRef<{ id: string; dx: number; dy: number } | null>(null);

  if (!open) return null;

  const selectedComp = components.find((c) => c.id === selected);

  const addComponent = (kind: GuiComponent['kind']) => {
    const c: GuiComponent = {
      id: 'c' + Math.random().toString(36).slice(2, 7),
      kind,
      x: 60 + Math.random() * 120,
      y: 60 + Math.random() * 100,
      w: kind === 'label' ? 160 : kind === 'toggle' ? 140 : 120,
      h: kind === 'panel' || kind === 'card' ? 100 : 32,
      text: kind[0].toUpperCase() + kind.slice(1),
      color: '#9333EA',
    };
    setComponents([...components, c]);
    setSelected(c.id);
  };

  const update = (patch: Partial<GuiComponent>) => {
    if (!selected) return;
    setComponents(components.map((c) => (c.id === selected ? { ...c, ...patch } : c)));
  };

  return (
    <div className="fixed inset-0 z-[70] flex items-center justify-center" style={{ background: 'rgba(0,0,0,0.55)' }} onClick={() => setOverlay('guiBuilder', false)}>
      <div
        className="flex h-[640px] w-[1000px] max-w-[96vw] overflow-hidden rounded-2xl border shadow-panel animate-fade-in"
        style={{ background: 'var(--wc-panel)', borderColor: 'var(--wc-border)' }}
        onClick={(e) => e.stopPropagation()}
      >
        {/* palette */}
        <div className="w-[150px] shrink-0 p-3" style={{ borderRight: '1px solid var(--wc-border)' }}>
          <div className="mb-2 text-[11px] font-semibold">Components</div>
          {palette.map((p) => (
            <button
              key={p.kind}
              className="mb-1 flex w-full items-center gap-2 rounded-lg px-2 py-1.5 text-[11px] transition-colors hover:bg-[var(--wc-hover)]"
              style={{ color: 'var(--wc-text)' }}
              onClick={() => addComponent(p.kind)}
            >
              <p.icon size={12} style={{ color: 'var(--wc-neon)' }} /> {p.label}
            </button>
          ))}
          <div className="mt-4 text-[10px] leading-relaxed" style={{ color: 'var(--wc-muted)' }}>
            Click to add, drag on canvas to move. Generate real code for HTML, Swing or Minecraft GUI.
          </div>
        </div>

        {/* canvas */}
        <div className="flex min-w-0 flex-1 flex-col">
          <div className="flex items-center gap-2 px-4 py-2.5" style={{ borderBottom: '1px solid var(--wc-border)' }}>
            <Sparkles size={13} style={{ color: 'var(--wc-neon)' }} />
            <span className="text-[12px] font-semibold">AI GUI Builder</span>
            <input className="wc-input ml-2 w-40 py-1 text-[11px]" value={name} onChange={(e) => setName(e.target.value)} placeholder="GUI name" />
            <select className="wc-input w-36 py-1 text-[11px]" value={target} onChange={(e) => setTarget(e.target.value as OutputKind)}>
              <option value="html">HTML / CSS</option>
              <option value="swing">Java Swing</option>
              <option value="minecraft">Minecraft GUI</option>
            </select>
            <button className="wc-btn ml-auto py-1 text-[10.5px]" onClick={() => setComponents([])}>
              <Undo2 size={11} /> Clear
            </button>
            <button
              className="wc-btn py-1 text-[10.5px]"
              onClick={() => {
                void navigator.clipboard?.writeText(generateCode(components, target, name));
                notify('success', 'Code copied to clipboard');
              }}
            >
              <Copy size={11} /> Copy code
            </button>
            <button
              className="wc-btn wc-btn-primary py-1 text-[10.5px]"
              onClick={async () => {
                if (!workspaceRoot) {
                  notify('warning', 'Open a project to save the generated GUI');
                  return;
                }
                const ext = target === 'html' ? 'html' : 'java';
                const rel = target === 'minecraft' ? `src/main/java/com/example/client/gui/${name}Screen.java` : target === 'swing' ? `src/main/java/${name}Frame.java` : `src/gui/${name}.html`;
                await window.wincode.writeFile(`${workspaceRoot}/${rel}`, generateCode(components, target, name));
                await useApp.getState().refreshTree();
                await useApp.getState().openFile(`${workspaceRoot}/${rel}`);
                notify('success', `Saved ${rel}`);
                setOverlay('guiBuilder', false);
              }}
            >
              <Save size={11} /> Save to project
            </button>
            <button className="rounded p-1 hover:bg-white/10" onClick={() => setOverlay('guiBuilder', false)}>
              <X size={14} />
            </button>
          </div>

          <div
            className="relative m-4 flex-1 overflow-hidden rounded-xl border"
            style={{
              borderColor: 'var(--wc-border)',
              background: 'linear-gradient(135deg,#09090F,#12121c)',
              backgroundImage:
                'radial-gradient(circle at 20% 20%, rgba(147,51,234,0.12), transparent 40%), radial-gradient(circle at 80% 70%, rgba(168,85,247,0.1), transparent 45%)',
            }}
            onMouseMove={(e) => {
              const drag = dragRef.current;
              if (!drag) return;
              const rect = (e.currentTarget as HTMLElement).getBoundingClientRect();
              const x = e.clientX - rect.left - drag.dx;
              const y = e.clientY - rect.top - drag.dy;
              setComponents((cs) => cs.map((c) => (c.id === drag.id ? { ...c, x: Math.round(x), y: Math.round(y) } : c)));
            }}
            onMouseUp={() => (dragRef.current = null)}
            onMouseLeave={() => (dragRef.current = null)}
          >
            {components.map((c) => (
              <div
                key={c.id}
                onMouseDown={(e) => {
                  e.stopPropagation();
                  setSelected(c.id);
                  const rect = (e.currentTarget.parentElement as HTMLElement).getBoundingClientRect();
                  dragRef.current = { id: c.id, dx: e.clientX - rect.left - c.x, dy: e.clientY - rect.top - c.y };
                }}
                className="absolute cursor-move transition-shadow"
                style={{
                  left: c.x,
                  top: c.y,
                  width: c.w,
                  height: c.h,
                  outline: selected === c.id ? '2px solid var(--wc-neon)' : '1px dashed rgba(255,255,255,0.12)',
                  borderRadius: c.kind === 'button' ? 10 : c.kind === 'card' || c.kind === 'panel' ? 14 : 6,
                  background:
                    c.kind === 'button'
                      ? `linear-gradient(135deg, ${c.color}, #A855F7)`
                      : c.kind === 'card'
                        ? `linear-gradient(135deg, ${c.color}, #A855F7)`
                        : c.kind === 'panel'
                          ? 'rgba(17,17,27,0.85)'
                          : 'transparent',
                  display: 'flex',
                  alignItems: 'center',
                  justifyContent: c.kind === 'label' ? 'flex-start' : 'center',
                  color: '#fff',
                  fontSize: 12,
                  boxShadow: c.kind === 'card' ? '0 12px 32px rgba(147,51,234,0.35)' : 'none',
                }}
              >
                {(c.kind === 'button' || c.kind === 'label' || c.kind === 'toggle') && c.text}
                {c.kind === 'input' && <span style={{ opacity: 0.5, paddingLeft: 10, fontSize: 11 }}>{c.text}</span>}
                {c.kind === 'slider' && (
                  <div className="mx-3 h-1.5 flex-1 rounded-full" style={{ background: 'rgba(255,255,255,0.2)' }}>
                    <div className="h-full w-1/2 rounded-full" style={{ background: c.color }} />
                  </div>
                )}
                {c.kind === 'toggle' && (
                  <div className="absolute right-2 h-4 w-8 rounded-full" style={{ background: c.color }}>
                    <div className="absolute right-0.5 top-0.5 h-3 w-3 rounded-full bg-white" />
                  </div>
                )}
              </div>
            ))}
          </div>
        </div>

        {/* properties */}
        <div className="w-[210px] shrink-0 p-3" style={{ borderLeft: '1px solid var(--wc-border)' }}>
          <div className="mb-2 text-[11px] font-semibold">Properties</div>
          {selectedComp ? (
            <div className="space-y-2.5">
              <div>
                <label className="mb-1 block text-[10px]" style={{ color: 'var(--wc-muted)' }}>Text</label>
                <input className="wc-input w-full text-[11px]" value={selectedComp.text} onChange={(e) => update({ text: e.target.value })} />
              </div>
              <div className="grid grid-cols-2 gap-1.5">
                {(['x', 'y', 'w', 'h'] as const).map((k) => (
                  <div key={k}>
                    <label className="mb-1 block text-[10px]" style={{ color: 'var(--wc-muted)' }}>{k.toUpperCase()}</label>
                    <input
                      type="number"
                      className="wc-input w-full text-[11px]"
                      value={selectedComp[k]}
                      onChange={(e) => update({ [k]: Number(e.target.value) } as Partial<GuiComponent>)}
                    />
                  </div>
                ))}
              </div>
              <div>
                <label className="mb-1 block text-[10px]" style={{ color: 'var(--wc-muted)' }}>Color</label>
                <input type="color" className="h-8 w-full cursor-pointer rounded" value={selectedComp.color} onChange={(e) => update({ color: e.target.value })} />
              </div>
              <button
                className="wc-btn w-full justify-center text-[10.5px]"
                style={{ color: '#EF4444' }}
                onClick={() => {
                  setComponents(components.filter((c) => c.id !== selected));
                  setSelected(null);
                }}
              >
                <X size={11} /> Delete component
              </button>
            </div>
          ) : (
            <div className="text-[10.5px]" style={{ color: 'var(--wc-muted)' }}>
              Select a component on the canvas to edit its properties.
            </div>
          )}

          <div className="mt-4">
            <button
              className="wc-btn w-full justify-center text-[10.5px]"
              onClick={() => setPreview(generateCode(components, target, name))}
            >
              <Code2 size={11} /> Preview generated code
            </button>
          </div>

          {preview && (
            <pre
              className="selectable mt-2 max-h-[220px] overflow-auto rounded-lg border p-2 font-mono text-[8.5px]"
              style={{ borderColor: 'var(--wc-border)', background: 'var(--wc-editor)', color: 'var(--wc-muted)' }}
            >
              {preview.slice(0, 3000)}
            </pre>
          )}
        </div>
      </div>
    </div>
  );
}
