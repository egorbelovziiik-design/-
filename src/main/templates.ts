export function templateFiles(o: MinecraftProjectOptions): Files {
  switch (o.type) {
    case 'fabric-mod': return fabricMod(o, false)
    case 'fabric-client': return fabricMod(o, true)
    case 'forge-mod': return forgeMod(o)
    case 'neoforge-mod': return neoForgeMod(o)
    case 'plugin': return paperPlugin(o)
    case 'launcher': return launcher(o)
  }
}

